--
--  Зачем это. Со страницы «Автор метода» убрана его биография —
--  школа, болезнь, спорт, травмы, медали, история прозвища. Но
--  помощник берёт факты не только из кода: всё, что команда
--  вносила в «Обучение ИИ» в админке, лежит в базе и попадает в
--  его ответы. Если что-то из убранного записано там, помощник
--  продолжит это рассказывать, хотя на сайте этого уже нет.
--
--  Запрос ниже показывает ВСЕ записи целиком — база небольшая, и
--  честнее прочитать её глазами, чем довериться поиску по словам.
--  Столбец «Похоже на биографию» — только подсказка, куда смотреть
--  в первую очередь.

select
  case
    when (title || ' ' || content) ~* '(чемпион|гепатит|медал|штанг|школ|травм|псевдоним|прозвищ|ташкент|олимп|джиу|грэпплинг|панкратион|борьб|бокс|mma|champion|hepatitis|medal|barbell|nickname)'
      then '⚠ посмотреть'
    else ''
  end                                            as "Похоже на биографию",
  case audience
    when 'client' then 'ИИ клиентов'
    when 'staff'  then 'ИИ Professor Python'
    else 'Оба ИИ'
  end                                            as "Кому видно",
  case when is_active then 'включено' else 'выключено' end as "Статус",
  title                                          as "Заголовок",
  content                                        as "Текст",
  id                                             as "Идентификатор"
from public.assistant_knowledge
order by
  case
    when (title || ' ' || content) ~* '(чемпион|гепатит|медал|штанг|школ|травм|псевдоним|прозвищ|ташкент|олимп|джиу|грэпплинг|панкратион|борьб|бокс|mma|champion|hepatitis|medal|barbell|nickname)'
      then 0 else 1
  end,
  created_at desc;

